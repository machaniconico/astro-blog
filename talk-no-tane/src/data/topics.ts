export function getTopicsByCategory(categoryId: string): Topic[] {
	return topics.filter((t) => t.category === categoryId);
}

// 日付を seed にした擬似乱数で「今日のネタ」を決定的に選ぶ（サーバー不要）。
export function getDailyTopic(date = new Date()): Topic {
	const seed =
		date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
	// xorshift 風の単純なハッシュ
	let x = seed;
	x ^= x << 13;
	x ^= x >> 17;
	x ^= x << 5;
	const index = Math.abs(x) % topics.length;
	return topics[index];
}
